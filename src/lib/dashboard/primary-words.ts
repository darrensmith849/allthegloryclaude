// "Mercies" -> "mercy", "redeemed" -> "redeem", "Spirit" -> "spirit".
export function primaryWordsFor(word: string): string[] {
  const w = word.trim().toLowerCase();
  const forms = [
    w,
    w.endsWith("ies") ? `${w.slice(0, -3)}y` : "",
    w.endsWith("s") ? w.slice(0, -1) : "",
    w.endsWith("ed") ? w.slice(0, -2) : "",
    w.endsWith("ed") ? w.slice(0, -1) : "",
    w.endsWith("ing") ? w.slice(0, -3) : "",
    w.endsWith("ing") ? `${w.slice(0, -3)}e` : "",
  ];
  for (const f of forms) if (f && PRIMARY_WORDS[f]) return PRIMARY_WORDS[f];
  return [];
}
